#!/usr/bin/env node
// The fff mark as a path light enough to ship in the app bundle, for the page loader that WRITES it
// (packages/web/src/components/FrizzLoader.tsx).
//
// final/fff.svg is a Catmull-Rom path through every 10th point of the dense row build-fff.mjs samples:
// 1357 cubic segments, 56KB. The loader draws it at 96px, where a stroke through every STEPth of those
// points is indistinguishable from it. The points are the ones the shipped path already passes through,
// so the loader cannot drift from the icon: rebuild the icon, then rebuild this.
//
//   nub build-loader.mjs              write packages/web/src/components/frizzMarkPath.ts
//   STEP=8 nub build-loader.mjs       finer (more segments, closer to the icon)
//   nub build-loader.mjs --dry        report the deviation without writing

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { catmullPath } from "./fit-two.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const STEP = Number(process.env.STEP ?? 12)
const svg = readFileSync(join(here, "final/fff.svg"), "utf8")
const d = /<path d="([^"]+)"/.exec(svg)[1]
const view = /viewBox="([^"]+)"/.exec(svg)[1]
const stroke = Number(/stroke-width="([^"]+)"/.exec(svg)[1])

// Every on-curve point of the shipped path: the M, then each C's last pair.
const nums = d.match(/-?\d+(\.\d+)?/g).map(Number)
const points = [[nums[0], nums[1]]]
for (let i = 2; i + 5 < nums.length + 1; i += 6) points.push([nums[i + 4], nums[i + 5]])

const kept = points.filter((_, i) => i % STEP === 0)
if (kept.at(-1) !== points.at(-1)) kept.push(points.at(-1))
const compact = catmullPath(kept)

// How far the compact stroke strays from the shipped one, in the mark's own units (stroke ${stroke}).
const sample = (path) => {
  const n = path.match(/-?\d+(\.\d+)?/g).map(Number)
  const out = []
  let p = [n[0], n[1]]
  for (let i = 2; i + 5 < n.length + 1; i += 6) {
    const [c1x, c1y, c2x, c2y, x, y] = n.slice(i, i + 6)
    for (let s = 0; s < 24; s += 1) {
      const t = s / 24
      const m = 1 - t
      out.push([
        m * m * m * p[0] + 3 * m * m * t * c1x + 3 * m * t * t * c2x + t * t * t * x,
        m * m * m * p[1] + 3 * m * m * t * c1y + 3 * m * t * t * c2y + t * t * t * y,
      ])
    }
    p = [x, y]
  }
  return out
}
const dense = sample(compact)
let worst = 0
for (const [x, y] of points) {
  let best = Infinity
  for (const [u, v] of dense) best = Math.min(best, (u - x) ** 2 + (v - y) ** 2)
  worst = Math.max(worst, Math.sqrt(best))
}
const [, , vw] = view.split(" ").map(Number)
console.log(`step ${STEP}: ${kept.length - 1} segments, ${compact.length} chars, worst deviation ${worst.toFixed(2)} units (${((worst / vw) * 96).toFixed(3)}px at 96px wide)`)

if (!process.argv.includes("--dry")) {
  const out = join(here, "../../packages/web/src/components/frizzMarkPath.ts")
  writeFileSync(
    out,
    `// GENERATED by assets/logo-concepts/build-loader.mjs from assets/logo-concepts/final/fff.svg — the fff mark
// as one stroke, light enough for the bundle. Rebuild it there; do not hand-edit.
export const FRIZZ_MARK_VIEWBOX = "${view}"
export const FRIZZ_MARK_STROKE = ${stroke}
export const FRIZZ_MARK_PATH =
  "${compact}"
`,
  )
  console.log(`wrote ${out}`)
}

import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { test } from "node:test";
import { serverReleaseMinimum, serverReleaseSpec } from "./server-release.ts";
import { WORKER_PLUGIN_REQUIRED_FILES } from "./worker-plugin-closure.ts";

/**
 * The published package is the REPO ROOT, so `files` is the only thing standing between npm and the
 * whole checkout — `plans/`, `attachments/`, `scratch/`, `.frizz/`, agent scratch directories, every worktree
 * under `.claude/`. When the package lived in `packages/cli` a mistake here shipped a few stray files;
 * now it can ship the repository. npm excludes `.git` and `node_modules` on its own and nothing else.
 *
 * These assertions are deliberately about the MANIFEST rather than a real `npm pack`: packing runs the
 * full prepack build (web bundle included), which is far too slow for the unit suite. What they catch
 * is the realistic regression — someone widening `files` — not a packing engine bug.
 */
const manifest = JSON.parse(
  readFileSync(join(import.meta.dirname, "..", "package.json"), "utf8")
) as { files?: string[]; bin?: Record<string, string>; name?: string; frizzServer?: unknown; dependencies?: Record<string, string> };
const serverManifest = JSON.parse(
  readFileSync(join(import.meta.dirname, "..", "packages", "server-release", "package.json"), "utf8")
) as { files?: string[]; name?: string; frizzServer?: unknown; dependencies?: Record<string, string>; optionalDependencies?: Record<string, string>; engines?: { node?: string } };
const sourceServerManifest = JSON.parse(
  readFileSync(join(import.meta.dirname, "..", "packages", "server", "package.json"), "utf8")
) as { dependencies?: Record<string, string> };

/** Build outputs only. Every entry is regenerated by prepack and none is checked in. */
const SHELL_PUBLISHED_PATHS = ["dist"];
const SERVER_PUBLISHED_PATHS = ["dist", "web-dist", "runtime"];

test("the published package ships only build output, never repository content", () => {
  assert.deepEqual(manifest.files, SHELL_PUBLISHED_PATHS);
  assert.deepEqual(serverManifest.files, SERVER_PUBLISHED_PATHS);
});

test("no files entry can escape the package root or widen to the whole checkout", () => {
  for (const entry of [...(manifest.files ?? []), ...(serverManifest.files ?? [])]) {
    assert.ok(!entry.startsWith("/"), `absolute files entry: ${entry}`);
    assert.ok(!entry.includes(".."), `files entry escapes the package root: ${entry}`);
    assert.ok(
      !["*", ".", "./", "**", "**/*"].includes(entry),
      `files entry publishes the entire checkout: ${entry}`
    );
  }
});

/**
 * `runtime/` is a COPY of `board/` and `cc-worker/`, so the closure the pack step asserts is only as
 * good as those source paths still existing. Renaming a required hook is otherwise caught by nothing
 * until prepack — or, for the frizz-dev path, until a promoted artifact fails to verify.
 */
test("every required worker-plugin file exists at the repo root the staged runtime mirrors", () => {
  const repo = join(import.meta.dirname, "..");
  assert.ok(WORKER_PLUGIN_REQUIRED_FILES.length > 0);
  for (const file of WORKER_PLUGIN_REQUIRED_FILES) {
    assert.ok(existsSync(join(repo, file)), `required worker-plugin file is missing from source: ${file}`);
  }
});

test("every bin target resolves inside a published directory", () => {
  const bins = Object.values(manifest.bin ?? {});
  assert.ok(bins.length > 0, "the package must expose a bin");
  for (const target of bins) {
    const normalized = target.replace(/^\.\//, "");
    assert.ok(
      SHELL_PUBLISHED_PATHS.some((dir) => normalized.startsWith(`${dir}/`)),
      `bin ${target} is not inside a published directory, so the installed CLI would be missing`
    );
  }
});

test("the shell bootstraps the versioned public server contract", () => {
  assert.deepEqual(manifest.frizzServer, {
    package: "frizz-server",
    version: "0.15.51",
    minimum: "0.15.48",
    protocol: 1,
    dataEpoch: 1,
  });
  assert.equal(serverManifest.name, "frizz-server");
  assert.deepEqual(serverManifest.frizzServer, { protocol: 1, dataEpoch: 1 });
  // The launcher parses both at every start and refuses a minimum its own pin does not meet, so a
  // manifest that would stop every launch has to fail here, before it is published.
  assert.equal(serverReleaseSpec(manifest).version, "0.15.51");
  assert.equal(serverReleaseMinimum(manifest), "0.15.48");
});

test("native server dependencies do not leak back into the stable shell", () => {
  // The shell is one bundled file. A dependency here is installed by every `npx frizz` and has to load
  // before the launcher can print `--help`: until 2026-11-10 that was the server's file watcher, a
  // native addon the registry launcher never starts (scripts/build-package.test.mjs runs the bundle).
  assert.equal(manifest.dependencies, undefined, "the shell declares a runtime dependency again");
  // Sign-in runs over pipes: no pty, so no native addon that needs a build on any platform.
  assert.equal(serverManifest.dependencies?.["node-pty"], undefined);
  assert.equal(sourceServerManifest.dependencies?.["node-pty"], undefined);
});

test("what a user's machine installs for the server is named exactly: the server and its watcher's binary", () => {
  // Until 2026-11-10 `frizz-server` depended on `@parcel/watcher`, whose own dependencies are four
  // semver ranges (`picomatch ^4.0.3`, …). The launcher's install resolved them on every user's machine,
  // at every install and update, with `--min-release-age=0` lifting the user's release-age guard for the
  // whole tree: a new patch of any of the four reached every Frizz that updated that day, unreviewed,
  // inside the process that holds the board's session keys.
  //
  // The watcher's JavaScript is in the server's bundle now, at the versions this workspace locked
  // (scripts/build-package.test.mjs). What is left to install is the binary, and a binary package has
  // no dependencies of its own.
  assert.equal(serverManifest.dependencies, undefined, "a dependency of the server is resolved, with its own ranges, on the user's machine");

  // Exactly the platform packages the watcher this workspace builds against names, at its version.
  const watcher = JSON.parse(
    readFileSync(createRequire(join(import.meta.dirname, "..", "packages", "server", "package.json")).resolve("@parcel/watcher/package.json"), "utf8")
  ) as { version: string; optionalDependencies: Record<string, string> };
  assert.equal(sourceServerManifest.dependencies?.["@parcel/watcher"], watcher.version, "the source server pins the watcher exactly");
  assert.ok(Object.keys(watcher.optionalDependencies).length >= 13);
  assert.deepEqual(serverManifest.optionalDependencies, watcher.optionalDependencies, "the published server names the watcher's binaries as the watcher itself does");
  for (const [name, version] of Object.entries(serverManifest.optionalDependencies ?? {})) {
    assert.match(name, /^@parcel\/watcher-[a-z0-9]+-[a-z0-9]+(-glibc|-musl)?$/);
    assert.equal(version, watcher.version, `${name} is not pinned to the watcher's own version`);
  }
});

test("server packages declare their actual runtime contracts", () => {
  assert.equal(serverManifest.engines?.node, "^22.13.0 || >=23.4.0");
  assert.equal(sourceServerManifest.dependencies?.["qrcode-generator"], "^2.0.4");
  assert.equal(serverManifest.dependencies?.["qrcode-generator"], undefined, "the public bundle embeds QR rendering");
});
